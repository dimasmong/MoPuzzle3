export class I18n {
  private static currentLang: Language = 'en';

  public static init(): void {
    const saved = Persistence.getInstance().getSettings().language;
    this.currentLang = saved || 'en';
  }

  public static getLanguage(): Language {
    return this.currentLang;
  }

  public static setLanguage(lang: Language): void {
    this.currentLang = lang;
    Persistence.getInstance().updateSettings({ language: lang });
    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('lang', lang);
    }
  }

  public static t(key: string): string {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    if (dict[key] !== undefined) {
      return dict[key];
    }
    const fallback = TRANSLATIONS.en[key];
    return fallback !== undefined ? fallback : key;
  }
}
